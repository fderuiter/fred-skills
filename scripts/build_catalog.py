"""Generate deterministic machine- and human-readable skill discovery indexes."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from skill_tools import ROOT, read_frontmatter, suite_members


def rendered_catalog(root: Path = ROOT) -> dict[str, str]:
    membership = suite_members(root)
    experience_path = root / "catalog/experience.json"
    experience = (
        json.loads(experience_path.read_text(encoding="utf-8"))["skills"]
        if experience_path.exists()
        else {}
    )
    entries = []
    for skill in sorted((root / "skills").glob("*/SKILL.md")):
        meta, body = read_frontmatter(skill)
        name = meta["name"]
        if not isinstance(name, str) or name != skill.parent.name:
            raise ValueError(f"Skill name/directory mismatch: {skill}")
        title = next(
            (line[2:].strip() for line in body.splitlines() if line.startswith("# ")),
            name,
        )
        entries.append(
            {
                "name": name,
                "title": title,
                "description": meta["description"],
                "path": skill.relative_to(root).as_posix(),
                **membership.get(
                    name, {"suite": None, "phase": None, "phase_title": None}
                ),
                **experience.get(name, {}),
            }
        )
    missing = set(membership) - {entry["name"] for entry in entries}
    if missing:
        raise ValueError(f"Suite members missing packages: {sorted(missing)}")
    markdown = "# Skill catalog\n\nGenerated by `python scripts/build_catalog.py`; edit the skill metadata and suite manifest.\n\n"
    markdown += "| Pass | Skill | Purpose |\n| --- | --- | --- |\n"
    for entry in sorted(
        entries,
        key=lambda item: (
            item["suite"] or "",
            item["phase"] if item["phase"] is not None else 99,
            item["name"],
        ),
    ):
        desc = entry["description"].replace("|", "\\|").replace("\n", " ")
        phase = entry["phase_title"] or "Independent"
        markdown += f"| {phase} | [{entry['name']}](../{entry['path']}) | {desc} |\n"
    return {
        "catalog/skills.json": json.dumps(
            {"schema_version": "1.0", "skills": entries}, indent=2, ensure_ascii=False
        )
        + "\n",
        "docs/catalog.md": markdown,
    }


def build(root: Path = ROOT, check: bool = False) -> list[str]:
    problems = []
    for relative, content in rendered_catalog(root).items():
        path = root / relative
        if check:
            if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
                problems.append(f"Stale generated index: {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        problems = build(check=args.check)
    except (OSError, ValueError, KeyError) as exc:
        parser.exit(1, f"Catalog generation failed: {exc}\n")
    for problem in problems:
        print(problem)
    if not problems:
        print("PASS: discovery catalogs are current")
    return bool(problems)


if __name__ == "__main__":
    raise SystemExit(main())
