"""Generate deterministic machine- and human-readable skill discovery indexes."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from skill_tools import ROOT, build_outputs, read_frontmatter, suite_members


def _pack_plugins(root: Path, known_skills: set[str]) -> list[dict[str, object]]:
    packs_path = root / "catalog/packs.json"
    if not packs_path.exists():
        return []
    packs = json.loads(packs_path.read_text(encoding="utf-8")).get("packs", {})
    bundles: list[dict[str, object]] = []
    for pack_name, pack_data in packs.items():
        if pack_name == "fred-skills" or pack_name in known_skills:
            raise ValueError(
                f"Pack name collides with reserved or skill name: {pack_name}"
            )
        pack_skills = pack_data.get("skills", [])
        missing = set(pack_skills) - known_skills
        if not pack_skills or missing:
            raise ValueError(
                f"Invalid skill selection in pack '{pack_name}': {sorted(missing)}"
            )
        bundles.append(
            {
                "name": pack_name,
                "description": pack_data["description"],
                "source": "./",
                "strict": False,
                "skills": [f"./skills/{skill_name}" for skill_name in pack_skills],
            }
        )
    return bundles


def rendered_catalog(root: Path = ROOT) -> dict[str, str]:
    membership = suite_members(root)
    for name in sorted(membership):
        entry_point = root / "skills" / name / "SKILL.md"
        if entry_point.is_symlink() or not entry_point.is_file():
            raise ValueError(f"Listed skill missing entry point file: {name}")
    experience_path = root / "catalog/experience.json"
    experience = (
        json.loads(experience_path.read_text(encoding="utf-8"))["skills"]
        if experience_path.exists()
        else {}
    )
    entries = []
    for skill in sorted((root / "skills").glob("*/SKILL.md")):
        meta, body = read_frontmatter(skill)
        name = meta["name"]
        if not isinstance(name, str) or name != skill.parent.name:
            raise ValueError(f"Skill name/directory mismatch: {skill}")
        title = next(
            (line[2:].strip() for line in body.splitlines() if line.startswith("# ")),
            name,
        )
        entries.append(
            {
                "name": name,
                "title": title,
                "description": meta["description"],
                "path": skill.relative_to(root).as_posix(),
                **membership.get(
                    name, {"suite": None, "phase": None, "phase_title": None}
                ),
                **experience.get(name, {}),
            }
        )
    missing = set(membership) - {entry["name"] for entry in entries}
    if missing:
        raise ValueError(f"Suite members missing packages: {sorted(missing)}")
    markdown = "# Skill catalog\n\nGenerated by `python scripts/build_catalog.py`; edit the skill metadata and suite manifest.\n\n"
    markdown += "| Pass | Skill | Purpose |\n| --- | --- | --- |\n"
    for entry in sorted(
        entries,
        key=lambda item: (
            item["suite"] or "",
            item["phase"] if item["phase"] is not None else 99,
            item["name"],
        ),
    ):
        desc = entry["description"].replace("|", "\\|").replace("\n", " ")
        phase = entry["phase_title"] or "Independent"
        markdown += f"| {phase} | [{entry['name']}](../{entry['path']}) | {desc} |\n"
    description = (
        "Portable engineering workflows for investigating repositories, planning"
        " useful fixes, and verifying that those fixes work."
    )
    suite_plugin: dict[str, object] = {
        "name": "fred-skills",
        "description": description,
        "source": "./",
        "strict": False,
        "skills": [f"./skills/{name}" for name in sorted(membership)],
    }
    standalone_plugins: list[dict[str, object]] = [
        {
            "name": entry["name"],
            "description": entry["description"],
            "source": f"./skills/{entry['name']}",
            "skills": ["."],
        }
        for entry in sorted(entries, key=lambda item: item["name"])
        if entry["name"] in membership
    ]
    plugins = [suite_plugin, *_pack_plugins(root, set(membership)), *standalone_plugins]
    version_path = root / "VERSION"
    extension_version = (
        version_path.read_text(encoding="utf-8").strip() or "0.0.0"
        if version_path.is_file()
        else "0.0.0"
    )
    marketplace_version_path = (
        version_path if version_path.is_file() else ROOT / "VERSION"
    )
    marketplace_version = (
        marketplace_version_path.read_text(encoding="utf-8").strip() or "0.0.0"
        if marketplace_version_path.is_file()
        else "0.0.0"
    )
    marketplace = {
        "name": "fred-skills",
        "version": marketplace_version,
        "description": description,
        "owner": {"name": "fderuiter"},
        "metadata": {
            "description": description,
            "version": marketplace_version,
        },
        "plugins": plugins,
    }
    marketplace_text = json.dumps(marketplace, indent=2, ensure_ascii=False) + "\n"
    gemini_extension = {
        "name": "fred-skills",
        "description": description,
        "version": extension_version,
    }
    return {
        "catalog/skills.json": (
            json.dumps(
                {"schema_version": "1.0", "skills": entries},
                indent=2,
                ensure_ascii=False,
            )
            + "\n"
        ),
        "docs/catalog.md": markdown,
        ".claude-plugin/marketplace.json": marketplace_text,
        ".cursor-plugin/marketplace.json": marketplace_text,
        "gemini-extension.json": (
            json.dumps(gemini_extension, indent=2, ensure_ascii=False) + "\n"
        ),
    }


def build(root: Path = ROOT, check: bool = False) -> list[str]:
    return build_outputs(rendered_catalog(root), root=root, check=check)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        problems = build(check=args.check)
    except (OSError, ValueError, KeyError) as exc:
        parser.exit(1, f"Catalog generation failed: {exc}\n")
    for problem in problems:
        print(problem)
    if not problems:
        print("PASS: discovery catalogs are current")
    return bool(problems)


if __name__ == "__main__":
    raise SystemExit(main())
